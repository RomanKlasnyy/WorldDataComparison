"""Generate docs/INDICATORS.md and docs/GROUPS.md from the configuration and dataset.

Run from the repository root:

    python tools/gen_docs.py
"""

from __future__ import annotations

import sys
from datetime import UTC, datetime
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from worlddata.config import GroupConfig, IndicatorConfig, load_config  # noqa: E402
from worlddata.db import DataError, open_repository, read_manifest  # noqa: E402
from worlddata.paths import get_paths  # noqa: E402

DIRECTION = {True: "Higher is better", False: "Lower is better", None: "Neutral"}


def esc(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def coverage_cell(row: pd.Series | None) -> str:
    if row is None or pd.isna(row.get("n_countries")):
        return "—"
    n = int(row["n_countries"])
    pct = float(row["pct"])
    return f"{pct:.1f}% ({n}/197)"


def latest_cell(row: pd.Series | None) -> str:
    if row is None or pd.isna(row.get("latest_year")):
        return "—"
    return str(int(row["latest_year"]))


def flags(indicator: IndicatorConfig) -> str:
    parts = []
    if indicator.default_log:
        parts.append("log")
    if indicator.is_composite:
        parts.append("composite")
    if indicator.hidden:
        parts.append("hidden")
    return ", ".join(parts) or "—"


def series_label(indicator: IndicatorConfig) -> str:
    if indicator.source == "derived" and indicator.derive:
        d = indicator.derive
        return f"{d.numerator} / {d.denominator} × {d.multiplier:g}"
    return indicator.series


def build_indicators(config, quality: pd.DataFrame, manifest: dict | None) -> str:
    lines: list[str] = []
    build_id = (manifest or {}).get("build_id", "not built")
    generated = datetime.now(UTC).strftime("%Y-%m-%d")
    lines.append("# Indicator catalogue\n")
    lines.append(
        "> Generated by `python tools/gen_docs.py` from `config/indicators.yaml` and "
        f"`data/quality_report.csv`. Do not edit by hand.  \n> Data build: `{build_id}` · "
        f"generated {generated}.\n"
    )
    lines.append(
        "Coverage is the share of the **197 default states** with a value at or after the "
        "recency cutoff (default 2015). Territories are excluded from this denominator. "
        "Direction affects percentile bars and best/worst labels, not the correlation math. "
        "`log` means log10 is applied by default on the Correlations page. `composite` means "
        "the index is built from other indicators and may be tautologically correlated with "
        "its components.\n"
    )

    sources = config.sources
    lines.append("## Sources\n")
    lines.append("| Source | Series | Licence | Attribution |")
    lines.append("| --- | --- | --- | --- |")
    for source in sources.values():
        lines.append(
            f"| {esc(source.name)} | {esc(source.id)} | {esc(source.license)} | "
            f"{esc(source.attribution)} |"
        )
    lines.append("")

    visible = [i for i in config.indicators if not i.hidden]
    by_domain: dict[str, list[IndicatorConfig]] = {}
    for indicator in visible:
        by_domain.setdefault(indicator.domain, []).append(indicator)

    totals = len(visible)
    covered = 0
    for indicator in visible:
        row = quality.loc[indicator.id] if indicator.id in quality.index else None
        if row is not None and not pd.isna(row.get("pct")) and float(row["pct"]) >= 60:
            covered += 1
    lines.append(
        f"**{totals} visible indicators** across {len(by_domain)} domains; "
        f"{covered} automated indicators reach ≥60% coverage. "
        f"Six indices require manual import (see below).\n"
    )

    for domain in config.domain_order:
        indicators = by_domain.get(domain)
        if not indicators:
            continue
        lines.append(f"## {domain}\n")
        lines.append(
            "| Indicator | Unit | Source | Series | Coverage | Latest | Direction | "
            "Group aggregation | Flags |"
        )
        lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
        for indicator in sorted(indicators, key=lambda i: i.name.casefold()):
            row = quality.loc[indicator.id] if indicator.id in quality.index else None
            source = sources.get(indicator.source)
            direction = DIRECTION.get(indicator.higher_is_better, "Neutral")
            lines.append(
                f"| **{esc(indicator.name)}**<br><code>{esc(indicator.id)}</code> | "
                f"{esc(indicator.unit)} | {esc(source.name if source else indicator.source)} | "
                f"`{esc(series_label(indicator))}` | {coverage_cell(row)} | {latest_cell(row)} | "
                f"{direction} | {esc(indicator.aggregation)} | {flags(indicator)} |"
            )
        lines.append("")

    hidden = [i for i in config.indicators if i.hidden]
    if hidden:
        lines.append("## Hidden inputs\n")
        lines.append(
            "These series are stored because a derived ratio needs them; they do not appear in "
            "pickers or correlations.\n"
        )
        lines.append("| Indicator | Unit | Source | Series | Coverage | Latest |")
        lines.append("| --- | --- | --- | --- | --- | --- |")
        for indicator in hidden:
            row = quality.loc[indicator.id] if indicator.id in quality.index else None
            lines.append(
                f"| **{esc(indicator.name)}**<br><code>{esc(indicator.id)}</code> | "
                f"{esc(indicator.unit)} | {esc(sources[indicator.source].name)} | "
                f"`{esc(indicator.series)}` | {coverage_cell(row)} | {latest_cell(row)} |"
            )
        lines.append("")

    manual = [i for i in visible if i.source == "manual"]
    if manual:
        lines.append("## Manual imports\n")
        lines.append(
            "These indices are not downloaded or redistributed. Import a CSV/XLSX with "
            "`country` (or ISO3 code), `year` and `value` columns:\n"
        )
        lines.append("```powershell")
        for indicator in manual:
            lines.append(
                f"python scripts/import_manual.py --indicator {indicator.id} --file {indicator.id}.csv"
            )
        lines.append("```\n")
        lines.append("| Indicator | Unit | Range | Direction | Notes |")
        lines.append("| --- | --- | --- | --- | --- |")
        for indicator in manual:
            range_text = f"{indicator.valid_min:g}–{indicator.valid_max:g}" if (
                indicator.valid_min is not None and indicator.valid_max is not None
            ) else "—"
            lines.append(
                f"| **{esc(indicator.name)}**<br><code>{esc(indicator.id)}</code> | "
                f"{esc(indicator.unit)} | {range_text} | "
                f"{DIRECTION.get(indicator.higher_is_better, 'Neutral')} | "
                f"{esc(indicator.attribution)} |"
            )
        lines.append("")

    lines.append("## Attribution\n")
    lines.append(
        "Per-indicator upstream attribution is stored in `config/indicators.yaml`; "
        "source-level licences are in the table above and in `NOTICE.txt`. "
        "Our World in Data series keep the terms of their upstream producers."
    )
    return "\n".join(lines).rstrip() + "\n"


def selector_text(group: GroupConfig) -> str:
    selector = group.selector
    if not selector:
        return "explicit member list"
    if selector.field:
        return f"`{selector.field} == {selector.equals}`"
    op = {"ge": "≥", "gt": ">", "le": "≤", "lt": "<", "eq": "="}.get(selector.op or "", "=")
    return f"`{selector.indicator} {op} {selector.value:g}`"


def build_groups(config, repo, manifest: dict | None) -> str:
    lines: list[str] = []
    build_id = (manifest or {}).get("build_id", "not built")
    generated = datetime.now(UTC).strftime("%Y-%m-%d")
    lines.append("# Country groups\n")
    lines.append(
        "> Generated by `python tools/gen_docs.py` from `config/groups.yaml` and the built "
        f"dataset. Do not edit by hand.  \n> Data build: `{build_id}` · generated {generated}.\n"
    )
    lines.append(
        "Groups are many-to-many and may overlap. Explicit membership is a fixed ISO3 list; "
        "selector membership is materialised at build time from country metadata or the "
        "latest indicator values at the build cutoff. Local edits in "
        "`data/groups.local.yaml` are not shown here. Edit definitions in "
        "`config/groups.yaml` and rebuild.\n"
    )

    group_rows = {}
    members_rows = {}
    if repo is not None:
        try:
            frame = repo.groups()
            group_rows = {row.id: row for row in frame.itertuples(index=False)}
            member_frame = repo.group_members()
            for row in member_frame.itertuples(index=False):
                members_rows.setdefault(row.group_id, []).append(row.iso3)
        except Exception:  # noqa: BLE001 - docs generation should not fail
            group_rows = {}
    if not group_rows:
        for group in config.groups:
            members_rows.setdefault(group.id, list(group.members))
            group_rows[group.id] = type(
                "R", (), {"id": group.id, "name": group.name, "family": group.family, "n_members": len(group.members)}
            )()

    family_names = {f.id: f.name for f in config.families}
    for family in config.families:
        groups = [g for g in config.groups if g.family == family.id]
        if not groups:
            continue
        lines.append(f"## {family.name}\n")
        lines.append("| Group | Type | Members | Definition | Rule |")
        lines.append("| --- | --- | --- | --- | --- |")
        for group in groups:
            row = group_rows.get(group.id)
            count = int(getattr(row, "n_members", 0) or 0)
            kind = "Selector" if group.selector else "Explicit"
            lines.append(
                f"| **{esc(group.name)}**<br><code>{esc(group.id)}</code> | {kind} | {count} | "
                f"{esc(group.description)} | {selector_text(group)} |"
            )
        lines.append("")

    lines.append("## Membership detail\n")
    lines.append(
        "The lists below are the materialised memberships for this build. A country may appear "
        "in several groups.\n"
    )
    lines.append("| Group | Family | Members (ISO3) |")
    lines.append("| --- | --- | --- |")
    for group in config.groups:
        members = sorted(members_rows.get(group.id, []))
        lines.append(
            f"| {esc(group.name)} | {esc(family_names.get(group.family, group.family))} | "
            f"{', '.join(members) if members else '—'} |"
        )
    lines.append("")
    lines.append(
        "Family names in the app are displayed as: "
        + ", ".join(f"{esc(f.name)} (`{esc(f.id)}`)" for f in config.families)
        + "."
    )
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    paths = get_paths()
    config = load_config(paths)
    docs = ROOT / "docs"
    docs.mkdir(parents=True, exist_ok=True)

    manifest = None
    try:
        manifest = read_manifest(paths)
    except DataError:
        manifest = None

    quality = pd.DataFrame(columns=["indicator_id"])
    if paths.quality_report.exists():
        quality = pd.read_csv(paths.quality_report).set_index("indicator_id")
        quality.index.name = "indicator_id"

    repo = None
    try:
        repo = open_repository(paths)
        if quality.empty:
            indicators = repo.indicators(include_hidden=True, with_data=True)
            quality = indicators.set_index("id")
    except DataError:
        repo = None

    indicators_md = build_indicators(config, quality, manifest)
    groups_md = build_groups(config, repo, manifest)
    (docs / "INDICATORS.md").write_text(indicators_md, encoding="utf-8")
    (docs / "GROUPS.md").write_text(groups_md, encoding="utf-8")
    if repo is not None:
        repo.close()
    print(f"wrote {docs / 'INDICATORS.md'}")
    print(f"wrote {docs / 'GROUPS.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
